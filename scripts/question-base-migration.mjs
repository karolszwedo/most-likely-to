// Snapshot of the shared question base for the database (S-17, context/changes/question-pool-in-db/plan.md, Faza 1
// #2). Makes a new migration, supabase/migrations/<timestamp>_question_base_snapshot.sql, that sets
// private.question_base (*_question_base.sql) to exactly the ids, categories and 18+ marks of src/data/questions.ts:
// one merge that updates the rows it matches, adds the new ones and deletes the ones the file no longer has. Run it
// after every change of the questions; the snapshot goes in the same PR, and `npx supabase db push` comes before the
// merge (the header of src/data/questions.ts). tests/unit/question-base-snapshot.test.ts is red until it runs.
//
// It only writes a local file. The file is created by `supabase migration new` (AGENTS.md), which writes the snapshot
// it is given on stdin; the CLI runs from the checkout's own node_modules with the current Node, never through npx or
// a shell, as runTool in .claude/hooks/lib.mjs does (on Windows npx is a .cmd file, which Node does not start without a
// shell). Nothing reaches a database, so `npm run questions:migration` needs no "ask" rule (lessons.md).
// `npm run questions:migration` passes --experimental-strip-types, which Node 22 (.nvmrc) needs to import the .ts file.
// Exit codes: 0 the snapshot is written, 1 nothing or not the whole snapshot was written (the message says which, and
// names every file the run left in supabase/migrations, to be deleted before the next run).
import { spawnSync } from "node:child_process";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { QUESTIONS } from "../src/data/questions.ts";

const ROOT = path.resolve(import.meta.dirname, "..");
const MIGRATIONS = path.join(ROOT, "supabase", "migrations");
const NAME = "question_base_snapshot";

// The first line of every snapshot: tests/unit/question-base-snapshot.test.ts finds the snapshots by it.
const MARKER =
  "-- question_base snapshot, generated by npm run questions:migration from src/data/questions.ts; do not edit";

// The formats of the table's checks. Every value goes into the SQL as a literal, so anything else stops the run before
// a file is made.
const QUESTION_ID = /^[a-z0-9-]+-[0-9]{3}$/;
const CATEGORY_ID = /^[a-z0-9-]+$/;

function fail(message) {
  console.error(`questions:migration: ${message}`);
  process.exit(1);
}

const entries = Object.entries(QUESTIONS);
if (entries.length === 0) fail("src/data/questions.ts has no question; nothing was written.");

const rows = entries.map(([id, entry]) => {
  if (!QUESTION_ID.test(id)) {
    fail(`the question id ${JSON.stringify(id)} is not <category-id>-<NNN>; nothing was written.`);
  }
  if (typeof entry.category !== "string" || !CATEGORY_ID.test(entry.category)) {
    fail(`the category of ${id} is not a category id; nothing was written.`);
  }
  if (typeof entry.adult !== "boolean") fail(`adult of ${id} is not true or false; nothing was written.`);
  return `    ('${id}', '${entry.category}', ${entry.adult})`;
});

const snapshot = [
  MARKER,
  `-- Sets private.question_base (*_question_base.sql) to exactly the ${rows.length} questions of the file, in its order:`,
  "-- a row it matches gets the file's category and 18+ mark, a new question is added, and a row the file no longer has",
  "-- is deleted. A change of the questions is a new snapshot (npm run questions:migration), never an edit of this one.",
  "",
  "merge into private.question_base as b",
  "using (",
  "  values",
  rows.join(",\n"),
  ") as s (question_id, category, adult)",
  "on b.question_id = s.question_id",
  "when matched then",
  "  update set category = s.category, adult = s.adult",
  "when not matched then",
  "  insert (question_id, category, adult) values (s.question_id, s.category, s.adult)",
  "when not matched by source then",
  "  delete;",
  "",
].join("\n");

// The CLI's launcher, as runTool resolves a tool's bin.
let cli = null;
try {
  const manifestPath = createRequire(path.join(ROOT, "package.json")).resolve("supabase/package.json");
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  const rel = typeof manifest.bin === "string" ? manifest.bin : manifest.bin?.supabase;
  if (typeof rel === "string") cli = path.join(path.dirname(manifestPath), rel);
} catch {
  cli = null;
}
if (cli === null) fail("the supabase package is not installed: run npm ci. Nothing was written.");

// Every file the run adds to supabase/migrations, of any name: a failure from here on names them, because a file the
// CLI created stays behind, empty or with part of the snapshot, and must not be committed or pushed.
const before = new Set(readdirSync(MIGRATIONS));
const added = () => readdirSync(MIGRATIONS).filter((name) => !before.has(name));

function failLeaving(message) {
  const left = added();
  fail(
    left.length === 0
      ? `${message} Nothing was written.`
      : `${message} Delete what it left in supabase/migrations before the next run: ${left.join(", ")}.`,
  );
}

const created = spawnSync(process.execPath, [cli, "migration", "new", NAME], {
  cwd: ROOT,
  input: snapshot,
  stdio: ["pipe", "inherit", "inherit"],
});
if (created.error !== undefined) {
  failLeaving(`supabase migration new did not start or did not end (${created.error.code ?? created.error.name}).`);
}
if (created.status === null) failLeaving(`supabase migration new was stopped by ${created.signal ?? "a signal"}.`);
if (created.status !== 0) failLeaving(`supabase migration new failed with exit code ${created.status}.`);

const snapshots = added().filter((name) => name.endsWith(`_${NAME}.sql`));
if (snapshots.length !== 1 || added().length !== 1) {
  failLeaving(`expected exactly one new file, *_${NAME}.sql, in supabase/migrations.`);
}

// The CLI writes what it gets on stdin into the new file. Should it ever leave the file empty or write something else,
// the snapshot is written here, so the file is always exactly the snapshot.
const file = path.join(MIGRATIONS, snapshots[0]);
try {
  if (readFileSync(file, "utf8") !== snapshot) {
    writeFileSync(file, snapshot);
    console.log("The CLI did not write the snapshot from stdin; it was written into the file it created.");
  }
} catch (error) {
  failLeaving(`the snapshot could not be checked or written (${error?.code ?? error?.name ?? "unknown error"}).`);
}

console.log(`supabase/migrations/${snapshots[0]}: ${rows.length} questions of src/data/questions.ts.`);
